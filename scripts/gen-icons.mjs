// Regenerate app/lib/icon-data.ts from the installed simple-icons package.
// Usage: node scripts/gen-icons.mjs
import { writeFileSync } from 'node:fs'
import * as si from 'simple-icons'

// order = atlas cell order (must stay stable; 'link' fallback is drawn by the atlas builder)
const ICONS = [
  ['instagram', 'siInstagram'],
  ['spotify', 'siSpotify'],
  ['tiktok', 'siTiktok'],
  ['discord', 'siDiscord'],
  ['x', 'siX'],
  ['youtube', 'siYoutube'],
  ['facebook', 'siFacebook'],
  ['twitch', 'siTwitch'],
  ['telegram', 'siTelegram'],
  ['line', 'siLine'],
  ['steam', 'siSteam'],
  ['github', 'siGithub'],
  ['valorant', 'siValorant'],
  ['roblox', 'siRoblox'],
  ['reddit', 'siReddit'],
]

const paths = {}
for (const [key, exportName] of ICONS) {
  const icon = si[exportName]
  if (!icon) {
    console.warn(`! missing icon: ${exportName}`)
    continue
  }
  paths[key] = icon.path
}

const out = `// AUTO-GENERATED by scripts/gen-icons.mjs — do not edit by hand.
// Run \`node scripts/gen-icons.mjs\` to regenerate.
export const ICON_PATHS: Record<string, string> = ${JSON.stringify(paths, null, 2)}

export const ICON_ALIASES: Record<string, string> = {
  twitter: 'x', yt: 'youtube', ytb: 'youtube', ig: 'instagram', fb: 'facebook',
  tt: 'tiktok', tg: 'telegram', spot: 'spotify', dc: 'discord', discordapp: 'discord',
  riot: 'valorant', game: 'valorant', web: 'link', website: 'link', url: 'link',
}

export function resolveIcon(name?: string | null): string {
  if (!name) return 'link'
  const key = name.toLowerCase().trim()
  const mapped = ICON_ALIASES[key] ?? key
  return ICON_PATHS[mapped] ? mapped : 'link'
}
`
writeFileSync(new URL('../app/lib/icon-data.ts', import.meta.url), out)
console.log(`wrote app/lib/icon-data.ts (${Object.keys(paths).length} icons)`)
